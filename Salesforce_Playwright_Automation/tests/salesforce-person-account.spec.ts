import fs from 'fs';
import path from 'path';
import { test } from '@playwright/test';
import { env } from '../src/config/env';
import { authStateFile } from '../src/config/paths';
import { LoginPage } from '../src/pages/LoginPage';
import { HomePage } from '../src/pages/HomePage';
import { AccountsPage } from '../src/pages/AccountsPage';
import { AccountRecordPage } from '../src/pages/AccountRecordPage';
import { currentDatePlusDays, formatDate } from '../src/utils/dateUtils';

const account = {
  fullName: 'Shreyansh Kumar',
  salutation: 'Mr.',
  firstName: 'Shreyansh',
  lastName: 'Kumar',
  phone: '8737373777',
  fax: '9838383',
  website: 'www.nestle.com',
  type: 'Analyst',
  industry: 'Banking',
  employees: '10',
  annualRevenue: '1000',
  description: 'This account created by Tosca tool',
};

const callComment = 'This text is generated by automation script';
const followUpComment = 'This follow-up task generated by Tosca tool';
const followUpDueDate = formatDate(currentDatePlusDays(3));

const followUpTask = {
  subject: 'Call',
  dueDate: followUpDueDate,
  comment: followUpComment,
  status: 'In Progress',
  priority: 'Low',
};

test.describe('Salesforce Lightning - Person Account lifecycle', () => {
  test('Login, create Person Account, log a call, add follow-up task, log out', async ({
    page,
  }) => {
    test.setTimeout(env.mfaTimeoutMs + 240_000);

    const loginPage = new LoginPage(page);
    const homePage = new HomePage(page);
    const accountsPage = new AccountsPage(page);
    const recordPage = new AccountRecordPage(page);

    await test.step('1. Launch Google Chrome and navigate to the Lightning app URL', async () => {
      await loginPage.goto(env.baseUrl);
    });

    await test.step('2-5. Enter the configured username/password and log in', async () => {
      await loginPage.login(env.username, env.password);
    });

    await test.step('5b. Complete identity verification (MFA) if prompted', async () => {
      await loginPage.completeIdentityVerification(
        env.verificationCode,
        env.mfaTimeoutMs,
      );
    });

    await test.step('6. Verify the Salesforce Lightning application is loaded', async () => {
      await homePage.expectLoaded();
    });

    await test.step('6b. Save the authenticated session for subsequent runs', async () => {
      fs.mkdirSync(path.dirname(authStateFile), { recursive: true });
      await page.context().storageState({ path: authStateFile });
    });

    await test.step('7. Open the App Launcher and open Accounts', async () => {
      await homePage.openApp('Accounts', '/lightning/o/Account/list');
    });

    await test.step('8. Click New and select the Person Account record type', async () => {
      await accountsPage.clickNew();
      await accountsPage.selectPersonAccountRecordType();
    });

    await test.step('9. Enter the Person Account details', async () => {
      await recordPage.selectPicklist('Salutation', account.salutation);
      await recordPage.fillText('First Name', account.firstName);
      await recordPage.fillText('Last Name', account.lastName);
      await recordPage.fillText('Phone', account.phone);
      await recordPage.fillText('Fax', account.fax);
      await recordPage.fillText('Website', account.website);
      await recordPage.selectPicklist('Type', account.type);
      await recordPage.selectPicklist('Industry', account.industry);
      await recordPage.fillText('Employees', account.employees);
      await recordPage.fillText('Annual Revenue', account.annualRevenue);
      await recordPage.fillText('Description', account.description);
    });

    await test.step('10. Click Save', async () => {
      await recordPage.save();
    });

    await test.step('11. Verify the Person Account was created', async () => {
      await recordPage.expectRecordLoaded(account.fullName);
    });

    await test.step('12. Verify all entered Account details were saved correctly', async () => {
      await recordPage.openDetailsTab();
      await recordPage.expectFieldValue('Account Name', account.fullName);
      await recordPage.expectFieldValue('Phone', account.phone);
      await recordPage.expectFieldValue('Fax', account.fax);
      await recordPage.expectFieldValue('Website', account.website);
      await recordPage.expectFieldValue('Type', account.type);
      await recordPage.expectFieldValue('Industry', account.industry);
      await recordPage.expectFieldValue('Employees', account.employees);
      await recordPage.expectFieldValue('Annual Revenue', account.annualRevenue);
      await recordPage.expectFieldValue('Description', account.description);
    });

    await test.step('13-17. From the Activity section, Log a Call with a comment and open the follow-up task', async () => {
      await recordPage.logCallAndCreateFollowUp(callComment);
    });

    await test.step('18-19. Set the follow-up task due date (today + 3 days) and save', async () => {
      await recordPage.saveFollowUpTask(followUpTask);
    });

    await test.step('20. Verify the call record was created', async () => {
      await recordPage.expectCallLogged();
    });

    await test.step('21-26. Open the follow-up task and set Subject, Status, Priority and Comments', async () => {
      await recordPage.openFollowUpTask();
      await recordPage.setFollowUpTaskDetails(followUpTask);
    });

    await test.step('27. Verify the follow-up task with the expected values', async () => {
      await recordPage.expectTaskDetails(followUpTask);
    });

    await test.step('23-25. Log out via the profile icon and verify the session ended', async () => {
      await homePage.logout();
      await page
        .locator('#username')
        .waitFor({ state: 'visible', timeout: 60_000 });
    });
  });
});
